let activeLanguage = typeof window === "undefined" ? "en" : window.localStorage.getItem("spendshield-language") || "en";
const textState = new WeakMap();
const attributeState = new WeakMap();

function translated(value, language) {
  if (language !== "hi") return value;
  const leading = value.match(/^\s*/)?.[0] || "";
  const trailing = value.match(/\s*$/)?.[0] || "";
  const core = value.slice(leading.length, value.length - trailing.length);
  let result = HINDI[core] || core;
  if (!HINDI[core]) {
    for (const month of ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"]) {
      result = result.replaceAll(month, HINDI[month]);
    }
  }
  return `${leading}${result}${trailing}`;
}

function translateNode(node) {
  const current = node.nodeValue;
  let state = textState.get(node);
  if (!state || current !== state.displayed) state = { source: current, displayed: current };
  const next = translated(state.source, activeLanguage);
  state.displayed = next;
  textState.set(node, state);
  if (current !== next) node.nodeValue = next;
}

function translateAttributes(element) {
  for (const name of ["placeholder", "aria-label", "title", "alt"]) {
    if (!element.hasAttribute?.(name)) continue;
    let attributes = attributeState.get(element);
    if (!attributes) { attributes = new Map(); attributeState.set(element, attributes); }
    const current = element.getAttribute(name);
    let state = attributes.get(name);
    if (!state || current !== state.displayed) state = { source: current, displayed: current };
    const next = translated(state.source, activeLanguage);
    state.displayed = next;
    attributes.set(name, state);
    if (current !== next) element.setAttribute(name, next);
  }
}

function translateTree(root) {
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (node.parentElement?.closest("script, style, textarea, [contenteditable='true']")) continue;
    translateNode(node);
  }
  if (root.nodeType === Node.ELEMENT_NODE) translateAttributes(root);
  root.querySelectorAll?.("[placeholder], [aria-label], [title], [alt]").forEach(translateAttributes);
}

let observer;
export function initializeLanguage() {
  document.documentElement.lang = activeLanguage === "hi" ? "hi" : "en";
  translateTree(document.body);
  observer?.disconnect();
  observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === "characterData") translateNode(record.target);
      for (const added of record.addedNodes || []) {
        if (added.nodeType === Node.TEXT_NODE) translateNode(added);
        else if (added.nodeType === Node.ELEMENT_NODE) translateTree(added);
      }
      if (record.type === "attributes") translateAttributes(record.target);
    }
  });
  observer.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ["placeholder", "aria-label", "title", "alt"] });
}

export function getLanguage() {
  return activeLanguage;
}

export function setLanguage(language) {
  activeLanguage = language === "hi" ? "hi" : "en";
  window.localStorage.setItem("spendshield-language", activeLanguage);
  document.documentElement.lang = activeLanguage;
  translateTree(document.body);
  window.dispatchEvent(new CustomEvent("spendshield-language-change", { detail: activeLanguage }));
}
